-- Run in the MEDICAL RECORDS Supabase project, not the Recurring Charges project.
-- Appointments remain in their existing table; preferences and subscriptions are isolated.
create table if not exists public.appointment_reminders (
  appointment_id text primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  enabled boolean not null default false,
  days_before integer not null default 3 check (days_before in (0,1,2,3,5,7,14,30)),
  updated_at timestamptz not null default now()
);
create index if not exists appointment_reminders_user_idx on public.appointment_reminders(user_id);
alter table public.appointment_reminders enable row level security;
drop policy if exists "Own appointment reminders" on public.appointment_reminders;
create policy "Own appointment reminders" on public.appointment_reminders for all to authenticated
using (auth.uid()=user_id and exists (
  select 1 from public.appointments a where a.id::text=appointment_id and a.user_id=auth.uid()
))
with check (auth.uid()=user_id and exists (
  select 1 from public.appointments a where a.id::text=appointment_id and a.user_id=auth.uid()
));

create table if not exists public.appointment_push_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  endpoint text not null unique,
  p256dh text not null,
  auth_key text not null,
  created_at timestamptz not null default now()
);
create index if not exists appointment_push_subscriptions_user_idx on public.appointment_push_subscriptions(user_id);
alter table public.appointment_push_subscriptions enable row level security;
drop policy if exists "Own appointment subscriptions" on public.appointment_push_subscriptions;
create policy "Own appointment subscriptions" on public.appointment_push_subscriptions for all to authenticated
using (auth.uid()=user_id) with check (auth.uid()=user_id);

create table if not exists public.appointment_push_sent (
  appointment_id text not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  subscription_id bigint not null references public.appointment_push_subscriptions(id) on delete cascade,
  reminder_date date not null,
  sent_at timestamptz not null default now(),
  primary key (appointment_id, subscription_id, reminder_date)
);
alter table public.appointment_push_sent enable row level security;
-- No browser policies: only the scheduled service-role function accesses the send log.

-- Remove reminder and send-log entries when their appointment is deleted.
create or replace function public.cleanup_appointment_reminder() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  delete from public.appointment_push_sent where appointment_id=old.id::text;
  delete from public.appointment_reminders where appointment_id=old.id::text;
  return old;
end; $$;
drop trigger if exists trg_cleanup_appointment_reminder on public.appointments;
create trigger trg_cleanup_appointment_reminder after delete on public.appointments
for each row execute function public.cleanup_appointment_reminder();
